// 她说话时头顶的气泡。
//
// 2026-11-11 01:3x：「在她的头上加一个框框，用来显示说话的文字，只有说话的时候，
// 框框才会出现，可以设置开关，之类的，框框的效果不要太差」
//
// 做法：**每次换一句话就重画一整张纹理**（背景 + 文字都画进同一张），运行时只画一个
// 带 alpha 的 quad。这样不用做文字排版缓存、不用管逐字绘制，换句时生成一次就够
// （一句 1~2 秒，生成一张 400×120 的图只要几毫秒）。
//
// 「效果不要太差」体现在这几处：
//   · 圆角 + 半透明深色底 + 细描边，不是生硬的纯色矩形
//   · 底下有一个小尖角指向她的头，看起来像在说话，不是贴上去的标签
//   · 出现时从 0.9 倍放大并淡入（0.16 秒），消失时淡出 + 稍微上浮（0.25 秒）
//   · 字距和行宽按字数自动撑开，两端留够内边距
//
// 用 FreeType 栅格化，字体是思源黑体（系统里现成）。
#pragma once

namespace bubble {

// 生命周期：main 每帧调 tick()，然后再 draw()。
void init();                                  // 载字体、建 GL 资源（失败就整块关掉）
void tick(double now, double dt);             // 推进动画、按需重建纹理
void draw(int winW, int winH);                // 画在窗口坐标系里（左下原点）
void say(const char* text, double now);       // 让她「说」一句：气泡出现/换词
void clear();                                 // 立刻收起
bool enabled();                               // 配置开着 且 字体加载成功
void setEnabled(bool on);
bool alive();                                 // 现在有没有东西要画（给主循环省事）

}  // namespace bubble
